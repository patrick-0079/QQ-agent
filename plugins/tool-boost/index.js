// 工具使用强化（确定性型 / plugins/）
//
// 为什么需要它：实测最近 40 个会话里，除 send_message 外几乎没有其它工具调用 ——
// 模型并不是"不想用"，而是（a）不知道手上有哪些工具，（b）被"像真人、别客服腔"的
// 人设压力压住了，（c）默认凭记忆答事实。
//
// 所以这段提示词做三件事：
//   1. 把「先查后答」写成硬规则，并给"常见偷懒借口 → 正确做法"对照表
//   2. 列一份工具清单（按用途，不逐个列 id，避免撑爆上下文）
//   3. 明确解除人设压力：**调工具不算出戏**，查完照样用短句/角色语气回
//
// 强度可调：strong（默认，硬性）/ normal（温和）/ off（不注入）。

const BUILD_TAG = 'v1.0.0';
let cfg = () => ({});
let log = () => {};

export function setup(api) {
  cfg = api.config || (() => ({}));
  log = api.log || (() => {});
  log(`工具使用强化已加载（${BUILD_TAG}）｜强度 ${cfg()?.strength || 'strong'}`);
}

const HARD = `# 工具优先（硬规则）
你一手上是有工具的，而且用它们**不会让你出戏**：查询、看链接、看图、看视频、记账、画图、提醒、翻本地资料，都是你自己的动作。**用工具不代表你变成客服** —— 查完照样用你原来的语气、短句回。为了像人而不用工具、凭记忆瞎答，才是失败。

**先查后答（硬性）**：遇到下面任何一类，先调工具，再开口：
1. 事实类问题（今天几号、天气、价格、新闻、某游戏/作品的数据、某个词是什么意思、某个东西怎么用）→ 先搜索，必要时点开网页看正文，再回答。
2. 有人发了**链接/卡片/B站视频** → 先读它（看视频类工具 / 网页抓取 / 本地知识库），再评论；读不到就说读不到，别猜内容。
3. 提到**过去说过的事、群友的约定、以前记过的东西** → 先翻记忆 / 本地知识库，再回答。
4. 有人问**你的看法、推荐、值不值得** → 可以搜一下再给带依据的看法，而不是凭印象。
5. 有人让你**记东西**（记仇、记账、记约定、记住某人）→ 用对应的写入工具真记下来，不要只在嘴上说"记住了"。
6. 有人要**图 / 画 / 地图 / 视频内容 / 语音** → 用对应的生成或读取工具；做不了就说做不了。

**常见偷懒借口 → 正确做法（自查表）**
- "这个我知道" → 知道也先确认；事实类一律先查。凭记忆答错，比多花两步糟得多。
- "随便聊聊，不用查" → 闲聊里出现可查的点（作品、人物、数据、梗的出处）同样要查。
- "太麻烦，直接答吧" → 该走几步就走几步：搜索 → 点开最相关的正文 → 再总结。
- "我在群里，别搞得像工具人" → 群里更要查；你查完只发一两句短话，没人知道中间发生了什么。
- "上一轮查过了" → 同一话题内可以复用，但**新话题重新查**，别把旧结论套上去。
- "查不到就算了" → 先说"我查一下"，再换关键词/换来源；真查不到才说查不到，并且说明你查过。

**每轮自问一次**：这件事，我手上的工具能不能做得更好？（搜索 / 读网页 / 读视频 / 看图 / 抽帧 / 画图 / 本地知识库 / 记忆 / 提醒 / 记账 / 电脑控制 / 状态查询）

**输出仍然要短**：工具给你的是原料，不是你说话的长度。查完依旧可以用一句、几个字回；**别把工具返回的原文倒给群友**。

工具清单（按用途找，名字以运行时工具表为准）：联网搜索与读网页 · 本地知识库（搜/读/记）· 长期记忆（写/查/删）· 消息收发与引用、表情包、拍一拍 · 看图片内容 · 读视频/音视频抽帧 · 画图与地图 · 提醒与待办 · 复仇账本账本类 · 群/会话状态、成本、天气、服务器状态 · 主人专属的电脑控制。`;

const SOFT = `# 多用工具（提示）
手上有工具就用起来：**事实类问题先搜索，有人发链接先读，问过去的事先翻记忆和本地库**。调工具不影响你的语气，查完照样短句回。别凭记忆答事实，也别把"在群里"当借口跳过检索。`;

export function promptSections() {
  const s = String(cfg()?.strength || 'strong').toLowerCase();
  if (s === 'off') return [];
  return [{
    id: 'tool-boost',
    title: '工具优先',
    priority: 92,
    content: s === 'normal' ? SOFT : HARD
  }];
}

export const internals = { HARD, SOFT, BUILD_TAG };
